#!/usr/bin/env swift
// Regenerates the app's colours from UI/tokens.json, the one place they are defined:
//
//   swift scripts/gen_palette.swift
//
// Writes PassFort/Support/PaletteTokens.swift and the AccentColor asset. Both are committed, so the
// app builds without running this; CI re-runs it and fails if either file has drifted from the
// tokens. Foundation only, nothing to install. Run from anywhere: paths resolve from this script.

import Foundation

// MARK: - Tokens

struct Pair: Decodable {
  let light: String
  let dark: String
}

struct Family: Decodable {
  let name: String
  let light: String
  let dark: String
  let categories: [String]
}

struct Tokens: Decodable {
  struct Semantic: Decodable {
    let success: Pair
    let warning: Pair
    let danger: Pair
    let favorite: Pair
  }
  struct Tile: Decodable {
    let lightAlpha: Double
    let darkAlpha: Double
  }
  let version: Int
  let brand: Pair
  let semantic: Semantic
  let tile: Tile
  let families: [Family]
}

func fail(_ message: String) -> Never {
  FileHandle.standardError.write(Data("gen_palette: \(message)\n".utf8))
  exit(1)
}

func warn(_ message: String) {
  FileHandle.standardError.write(Data("gen_palette: warning: \(message)\n".utf8))
}

// MARK: - Validation

/// `"#RRGGBB"` → its three channels, or `nil` when malformed.
func channels(_ hex: String) -> (r: Int, g: Int, b: Int)? {
  guard hex.count == 7, hex.hasPrefix("#"), let rgb = Int(hex.dropFirst(), radix: 16) else {
    return nil
  }
  return ((rgb >> 16) & 0xFF, (rgb >> 8) & 0xFF, rgb & 0xFF)
}

func checkHex(_ hex: String, _ where_: String) {
  if channels(hex) == nil { fail("\(where_): \"\(hex)\" is not #RRGGBB") }
}

func isIdentifier(_ name: String) -> Bool {
  guard let first = name.unicodeScalars.first, CharacterSet.lowercaseLetters.contains(first) else {
    return false
  }
  return name.unicodeScalars.allSatisfy { CharacterSet.alphanumerics.contains($0) && $0.isASCII }
}

/// WCAG 2 contrast ratio of `hex` against white.
func contrastWithWhite(_ hex: String) -> Double {
  guard let (r, g, b) = channels(hex) else { return 0 }
  func linear(_ c: Int) -> Double {
    let s = Double(c) / 255
    return s <= 0.04045 ? s / 12.92 : pow((s + 0.055) / 1.055, 2.4)
  }
  let luminance = 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b)
  return 1.05 / (luminance + 0.05)
}

func validate(_ tokens: Tokens) {
  guard tokens.version == 1 else { fail("unsupported tokens version \(tokens.version)") }
  let pairs: [(String, Pair)] = [
    ("brand", tokens.brand), ("semantic.success", tokens.semantic.success),
    ("semantic.warning", tokens.semantic.warning), ("semantic.danger", tokens.semantic.danger),
    ("semantic.favorite", tokens.semantic.favorite),
  ]
  for (name, pair) in pairs {
    checkHex(pair.light, "\(name).light")
    checkHex(pair.dark, "\(name).dark")
  }
  for alpha in [tokens.tile.lightAlpha, tokens.tile.darkAlpha] where !(0...1).contains(alpha) {
    fail("tile alphas must be between 0 and 1")
  }
  var seen = Set<String>()
  for family in tokens.families {
    guard isIdentifier(family.name) else { fail("family name \"\(family.name)\" is not lowerCamel") }
    checkHex(family.light, "families.\(family.name).light")
    checkHex(family.dark, "families.\(family.name).dark")
    for category in family.categories {
      guard isIdentifier(category) else { fail("category \"\(category)\" is not lowerCamel") }
      guard seen.insert(category).inserted else { fail("category \"\(category)\" is listed twice") }
    }
  }
  // A missing or misspelt category is not checked here: the generated switch over
  // AccountCategory fails to compile, which names it.

  // Buttons and list selection draw white text on the brand colour.
  let light = contrastWithWhite(tokens.brand.light)
  let dark = contrastWithWhite(tokens.brand.dark)
  if light < 4.5 {
    warn(String(format: "brand.light with white text is %.2f:1, below WCAG AA 4.5:1", light))
  }
  if dark < 3 {
    warn(String(format: "brand.dark with white text is %.2f:1, below 3:1 for controls", dark))
  }
}

// MARK: - Output

func pair(_ p: Pair) -> String { "HexPair(light: \"\(p.light)\", dark: \"\(p.dark)\")" }

func swiftSource(_ tokens: Tokens) -> String {
  let cases = tokens.families.map(\.name).joined(separator: ", ")
  let hexes = tokens.families.map { "    case .\($0.name): \(pair(Pair(light: $0.light, dark: $0.dark)))" }
  let mapping = tokens.families.map { family in
    "    case \(family.categories.map { ".\($0)" }.joined(separator: ", ")): .\(family.name)"
  }
  return """
    // GENERATED by scripts/gen_palette.swift from UI/tokens.json. Do not edit by hand:
    // change UI/tokens.json, then run `swift scripts/gen_palette.swift`.

    import PassFortVault

    /// The raw colour values. `Palette` turns them into appearance-aware `Color`s.
    enum PaletteTokens {
      static let brand = \(pair(tokens.brand))
      static let success = \(pair(tokens.semantic.success))
      static let warning = \(pair(tokens.semantic.warning))
      static let danger = \(pair(tokens.semantic.danger))
      static let favorite = \(pair(tokens.semantic.favorite))
      /// Opacity of a family colour behind its glyph, in Aqua and in Dark Aqua.
      static let tileLightAlpha = \(tokens.tile.lightAlpha)
      static let tileDarkAlpha = \(tokens.tile.darkAlpha)
    }

    /// The colour families categories share, so the vault reads as a few hues rather than one per
    /// category.
    enum PaletteFamily: CaseIterable {
      case \(cases)

      var hex: HexPair {
        switch self {
    \(hexes.joined(separator: "\n"))
        }
      }
    }

    extension AccountCategory {
      var family: PaletteFamily {
        switch self {
    \(mapping.joined(separator: "\n"))
        }
      }
    }

    """
}

func component(_ value: Int) -> String { String(format: "0x%02X", value) }

/// One entry of an asset catalog colour set, as the lines Xcode itself writes.
func colorEntry(_ hex: String, dark: Bool) -> [String] {
  guard let (r, g, b) = channels(hex) else { fail("unreachable: \(hex) was validated") }
  var lines = ["{"]
  if dark {
    lines += [
      "  \"appearances\" : [", "    {", "      \"appearance\" : \"luminosity\",",
      "      \"value\" : \"dark\"", "    }", "  ],",
    ]
  }
  lines += [
    "  \"color\" : {", "    \"color-space\" : \"srgb\",", "    \"components\" : {",
    "      \"alpha\" : \"1.000\",", "      \"blue\" : \"\(component(b))\",",
    "      \"green\" : \"\(component(g))\",", "      \"red\" : \"\(component(r))\"", "    }",
    "  },", "  \"idiom\" : \"universal\"", "}",
  ]
  return lines
}

/// The AccentColor set: the brand colour in Aqua and Dark Aqua. The global accent colour build
/// setting points at it, so AppKit-drawn controls (focus rings, selection) match `.tint`.
func accentColorJSON(_ tokens: Tokens) -> String {
  var light = colorEntry(tokens.brand.light, dark: false)
  light[light.count - 1] += ","
  let entries = (light + colorEntry(tokens.brand.dark, dark: true)).map { "    " + $0 }
  let lines =
    ["{", "  \"colors\" : ["] + entries
    + ["  ],", "  \"info\" : {", "    \"author\" : \"xcode\",", "    \"version\" : 1", "  }", "}"]
  return lines.joined(separator: "\n") + "\n"
}

// MARK: - Main

let script = URL(fileURLWithPath: CommandLine.arguments[0]).standardizedFileURL
let root = script.deletingLastPathComponent().deletingLastPathComponent()
let tokensURL = root.appending(path: "UI/tokens.json")

let tokens: Tokens
do {
  tokens = try JSONDecoder().decode(Tokens.self, from: Data(contentsOf: tokensURL))
} catch {
  fail("can't read \(tokensURL.path): \(error)")
}
validate(tokens)

let outputs: [(String, String)] = [
  ("PassFort/Support/PaletteTokens.swift", swiftSource(tokens)),
  ("PassFort/Assets.xcassets/AccentColor.colorset/Contents.json", accentColorJSON(tokens)),
]
for (path, text) in outputs {
  do {
    try Data(text.utf8).write(to: root.appending(path: path), options: .atomic)
    print("wrote \(path)")
  } catch {
    fail("can't write \(path): \(error)")
  }
}
